-- Additive migration (MySQL 8.0). Back up and review history before applying to an existing DB.
-- One PENDING proposal per (project, member) is enforced in the service under the proposer's row lock,
-- because MySQL has no partial unique index.
CREATE TABLE project_proposal (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    project_id BIGINT NOT NULL,
    proposer_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    job_position_id BIGINT NOT NULL,
    message VARCHAR(300) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL,
    created_at DATETIME(6) NULL,
    edited_at DATETIME(6) NULL,
    INDEX idx_proposal_proposer_created (proposer_id, created_at),
    INDEX idx_proposal_member (member_id, status),
    CONSTRAINT fk_proposal_project FOREIGN KEY (project_id) REFERENCES project (project_id),
    CONSTRAINT fk_proposal_proposer FOREIGN KEY (proposer_id) REFERENCES member (member_id),
    CONSTRAINT fk_proposal_member FOREIGN KEY (member_id) REFERENCES member (member_id),
    CONSTRAINT fk_proposal_job_position FOREIGN KEY (job_position_id) REFERENCES job_position (job_position_id)
);

-- A schema generated by Hibernate 6 may store notification.type as a native ENUM of the old values,
-- which would reject PROJECT_PROPOSAL_RECEIVED. VARCHAR accepts every NotificationType.
ALTER TABLE notification
    MODIFY COLUMN type VARCHAR(255) NULL,
    ADD COLUMN proposal_id BIGINT NULL,
    ADD CONSTRAINT fk_notification_proposal FOREIGN KEY (proposal_id) REFERENCES project_proposal (id);
